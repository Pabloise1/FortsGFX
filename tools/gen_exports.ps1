# Regenerates src/gen/{exports.def,stubs.asm,entries.inc} from src/exports.txt.
# Any export that has a hand-written `extern "C" ... WINAPI hk_<name>(` in src/hooks.cpp
# is exported from that wrapper; every other export gets a generic pass-through stub.
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$exports = Get-Content "$root\src\exports.txt" | Where-Object { $_ -match '\S' } | ForEach-Object { $_.Trim() }

$hooked = @{}
foreach ($m in (Select-String -Path "$root\src\hooks.cpp" -Pattern 'extern "C" [^\r\n(]*WINAPI hk_(\w+)\(' -AllMatches)) {
    foreach ($g in $m.Matches) { $hooked[$g.Groups[1].Value] = $true }
}

$def = @('LIBRARY opengl32', 'EXPORTS')
$asm = @('; generated by tools/gen_exports.ps1 - do not edit', 'EXTERN GenericThunk:PROC', 'EXTERN g_entries:BYTE', '', '.code', '')
$inc = @('// generated by tools/gen_exports.ps1 - do not edit')
$i = 0
foreach ($n in $exports) {
    if ($hooked.ContainsKey($n)) { $def += "    $n = hk_$n"; continue }
    $def += "    $n = stub_$n"
    $asm += "stub_$n PROC", "    lea r10, [g_entries + $($i * 32)]", "    jmp GenericThunk", "stub_$n ENDP"
    $inc += "    { nullptr, `"$n`" },"
    $i++
}
$asm += '', 'END'

$gen = "$root\src\gen"
New-Item -ItemType Directory -Force $gen | Out-Null
$def | Set-Content -Encoding ascii "$gen\exports.def"
$asm | Set-Content -Encoding ascii "$gen\stubs.asm"
$inc | Set-Content -Encoding ascii "$gen\entries.inc"
Write-Host "gen_exports: $($exports.Count) exports, $($exports.Count - $i) hand-wrapped, $i generic"
